os.makedirs(SCRIPT_D, exist_ok=True)

naskah_lines = []
batches = {}
for i, (tts_text, scene, overlay) in enumerate(BEATS, start=1):
    num = f"{i:03d}"
    line = f"BEAT-{num}: {tts_text}"
    if overlay:
        line += f"  [OVERLAY: {overlay}]"
    naskah_lines.append(line)
    with open(os.path.join(SCRIPT_D, f"b10-beat-{num}.txt"), "w") as f:
        f.write(f"BEAT-{num}: {tts_text}")
    batch_idx = (i - 1) // 4  # 18 batches of 4 -> one subagent per batch
    batches.setdefault(str(batch_idx), []).append({
        "num": num,
        "tts": tts_text,
        "img": STYLE + scene + ". No text, no watermark.",
        "overlay": overlay,
    })

with open(os.path.join(W, "script", "naskah-2026-10-10.txt"), "w") as f:
    f.write("\n".join(naskah_lines) + "\n")

with open(os.path.join(DATA_D, "batches-b10.json"), "w") as f:
    json.dump(batches, f, indent=1)

words = sum(len(t.split()) for t, _, _ in BEATS)
print(f"beats: {len(BEATS)}, words: {words}")
print("batches:", len(batches))
